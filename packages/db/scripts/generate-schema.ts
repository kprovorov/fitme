import { execFileSync } from "node:child_process";
import { readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Regenerates src/schema.ts and src/relations.ts from the running local stack
 * with `drizzle-kit pull` (see drizzle.config.ts), then normalizes them so a
 * rerun against the same migrations is byte-identical: declarations sorted by
 * name (pull lists tables in catalog order) and Biome formatting. The Database
 * Types workflow fails when the committed files differ from the output.
 */

const PULL_DIR = ".drizzle";
const GENERATED = ["schema.ts", "relations.ts"] as const;
const DECLARATION_START = /\n(?=export const )/;
const SCHEMA_DECLARATION = /^export const \w+ = pgSchema\(/;
// pull names the `private` schema `private`, a reserved word in modules
const PRIVATE_SCHEMA = /\bprivate(?=( = pgSchema\(|\.table\())/g;
// pull unescapes an empty text default ('') into a lone quote: `.default(')`
const EMPTY_TEXT_DEFAULT = /\.default\('\)/g;

const pnpmExec = (command: string, args: string[]) =>
  execFileSync("pnpm", ["exec", command, ...args], { stdio: "inherit" });

// By name (each starts `export const <name> `), in code-unit order rather
// than localeCompare so it's the same on every machine and locale
const byName = (a: string, b: string) => {
  if (a === b) {
    return 0;
  }
  return a < b ? -1 : 1;
};

const normalize = (source: string) => {
  const [header, ...declarations] = source
    .replace(PRIVATE_SCHEMA, "privateSchema")
    .replace(EMPTY_TEXT_DEFAULT, '.default("")')
    .split(DECLARATION_START);
  // pgSchema(…) objects first: tables are declared through them
  const isSchema = (declaration: string) =>
    SCHEMA_DECLARATION.test(declaration);
  const sorted = declarations
    .map((declaration) => declaration.trim())
    .sort((a, b) => Number(isSchema(b)) - Number(isSchema(a)) || byName(a, b));
  return [
    "// Generated by `pnpm --filter @fitme/db schema:generate`. Do not edit.",
    header.trim(),
    ...sorted,
  ].join("\n\n");
};

rmSync(PULL_DIR, { force: true, recursive: true });
try {
  pnpmExec("drizzle-kit", ["pull", "--config", "drizzle.config.ts"]);
  for (const file of GENERATED) {
    const source = readFileSync(join(PULL_DIR, file), "utf8");
    writeFileSync(join("src", file), `${normalize(source)}\n`);
  }
} finally {
  rmSync(PULL_DIR, { force: true, recursive: true });
}
pnpmExec("biome", [
  "check",
  "--write",
  "--unsafe",
  ...GENERATED.map((file) => join("src", file)),
]);
