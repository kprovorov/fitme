/// <reference types="node" />
// Writes the two declaration files Metro generates in apps/mobile, both
// gitignored, so a checkout typechecks and lints the mobile app before Metro
// has ever run (setup.sh, CI's `checks` job and the app's own `typecheck`
// script call it):
//
// - expo-env.d.ts, which `expo start` writes: expo/types supplies ProcessEnv
//   and widens ViewStyle with web props.
// - uniwind-types.d.ts, which uniwind's Metro plugin writes on every bundle:
//   it types uniwind's themes. It used to be committed, but the formatter
//   rewrites uniwind's format and Metro writes it back, so every Metro run
//   left it changed (FIT-369, FIT-844).
//
// A file already there (Metro's own) is left alone. Node in its own file, not a
// heredoc in setup.sh (bash 3.2, see AGENTS.md Shell).
//
// Usage: node scripts/mobile-types.mjs [mobile app directory]

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const EXPO_ENV = '/// <reference types="expo/types" />\n';

// Exactly what uniwind's Metro plugin writes for this app's themes
// (uniwind/dist/common/bundler/artifacts/dts.js), so Metro never rewrites it.
export const UNIWIND_TYPES = [
  "// NOTE: This file is generated by uniwind and it should not be edited manually.",
  '/// <reference types="uniwind/types" />',
  "",
  "declare module 'uniwind' {",
  "    export interface UniwindConfig {",
  "        themes: readonly ['light', 'dark']",
  "    }",
  "}",
  "",
  "export {}",
  "",
].join("\n");

export const GENERATED_FILES = {
  "expo-env.d.ts": EXPO_ENV,
  "uniwind-types.d.ts": UNIWIND_TYPES,
};

/**
 * Writes each generated file missing from the mobile app directory.
 *
 * @param {string} mobileDir The apps/mobile directory.
 * @returns {string[]} The names of the files it wrote.
 */
export const writeMobileTypes = (mobileDir) => {
  const written = [];

  for (const [name, content] of Object.entries(GENERATED_FILES)) {
    const file = path.join(mobileDir, name);

    if (!fs.existsSync(file)) {
      fs.writeFileSync(file, content);
      written.push(name);
    }
  }

  return written;
};

if (process.argv[1] === import.meta.filename) {
  const mobileDir =
    process.argv[2] ??
    fileURLToPath(new URL("../apps/mobile", import.meta.url));

  for (const name of writeMobileTypes(mobileDir)) {
    console.log(`wrote ${path.join(mobileDir, name)}`);
  }
}
